const undoLast = tool({
  name: 'undo_last_change',
  description: 'Take back the most recent changes made by AI (Abood or a connected app), newest first. Count defaults to 1.',
  inputSchema: { type: 'object', properties: { count: { type: 'integer', minimum: 1, maximum: 10 } }, additionalProperties: false },
  readOnly: false,
  async run(args, ctx) {
    const n = int(args, 'count', 1, 10) ?? 1;
    const rows: ChangeRow[] =
      (await must(
        ctx.db
          .from('connector_changes')
          .select('id, client_id, tool, target_table, target_id, before, summary, created_at, undone_at')
          .eq('user_id', ctx.userId)
          .is('undone_at', null)
          .order('created_at', { ascending: false })
          .limit(n),
      )) ?? [];
    if (!rows.length) return json({ unchanged: 'There is nothing to undo.' });
    const undone: string[] = [];
    for (const c of rows) {
      await applyUndo(ctx.db, ctx.userId, c, ctx.now);
      undone.push(c.summary);
    }
    return json({ undone, plan: await replanAfter(ctx) });
  },
});

