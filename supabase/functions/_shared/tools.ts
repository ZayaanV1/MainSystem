function num(args: Record<string, unknown>, key: string, min: number, max: number): number | null {
  const v = args[key];
  if (v === undefined || v === null) return null;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < min || v > max) throw new ToolError(`"${key}" must be a number from ${min} to ${max}.`);
  return v;
}

function clears(args: Record<string, unknown>): Set<string> {
  const v = args.clear;
  if (v === undefined || v === null) return new Set();
  if (!Array.isArray(v) || v.some((x) => typeof x !== 'string')) throw new ToolError('"clear" must be a list of field names.');
  return new Set(v as string[]);
}

function dayList(args: Record<string, unknown>, key: string): string[] {
  const v = args[key];
  if (v === undefined || v === null) return [];
  if (!Array.isArray(v)) throw new ToolError(`"${key}" must be a list of dates.`);
  return v.map((_, i) => day({ d: v[i] }, 'd', true) as string);
}

function weekdays(args: Record<string, unknown>, key: string): number[] | null {
  const v = args[key];
  if (v === undefined || v === null) return null;
  if (!Array.isArray(v) || v.some((x) => typeof x !== 'number' || !Number.isInteger(x) || x < 1 || x > 7)) {
    throw new ToolError(`"${key}" must be ISO weekdays, 1 (Monday) to 7 (Sunday).`);
  }
  return [...new Set(v as number[])].sort();
}

const hhmm = (minutes: number) => `${String(Math.floor(minutes / 60)).padStart(2, '0')}:${String(minutes % 60).padStart(2, '0')}`;
const toMinutes = (t: string) => Number(t.slice(0, 2)) * 60 + Number(t.slice(3));

/** The changed fields' earlier values, for the undo log. */
function pick(row: Record<string, unknown>, patch: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.keys(patch).map((k) => [k, row[k] ?? null]));
}

async function owned(ctx: ConnectorCtx, table: string, id: string, cols = '*') {
  const row = await must(ctx.db.from(table).select(cols).eq('user_id', ctx.userId).eq('id', id).maybeSingle());
  if (!row) throw new ToolError(NOT_FOUND);
  return row;
}

/** Write, record, and take the write back if recording fails: a change nobody can undo is not made. */
async function commit(
  ctx: ConnectorCtx,
  tool: string,
  table: string,
  id: string,
  before: unknown,
  summary: string,
  rollback: () => Promise<unknown>,
) {
  const err = await record(ctx, tool, table, id, before, summary);
  if (err) {
    await rollback();
    throw new Error(err.message);
  }
}

async function update(ctx: ConnectorCtx, table: string, id: string, patch: Record<string, unknown>) {
  const key = table === 'course_pages' ? 'course_id' : table === 'app_settings' ? 'user_id' : 'id';
  await must(ctx.db.from(table).update(patch).eq('user_id', ctx.userId).eq(key, id).select(key));
}

/** Replanning after a change the plan depends on. A failure is said, never thrown: the edit itself landed. */
async function replanAfter(ctx: ConnectorCtx): Promise<string | undefined> {
  try {
    const r = await replan(ctx.db, ctx.userId, ctx.tz, ctx.now);
    if (r.disabled) return undefined;
    return r.moved || r.added ? `Plan updated: ${r.moved} block${r.moved === 1 ? '' : 's'} moved, ${r.added} placed.` : undefined;
  } catch (e) {
    return `The plan could not be updated just now (${(e as Error).message}); it will catch up next time the app opens.`;
  }
}

