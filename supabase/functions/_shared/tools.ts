/**
 * Editing anything (6 Nov 2026): "he should be an ai assistant … edit any
 * assignment course or item in the app".
 *
 * One tool layer for Abood and for an AI app connected through functions/mcp,
 * so a change made by either is checked the same way and taken back from the
 * same list. Every write is recorded in connector_changes with what it
 * overwrote; a delete records the whole row and whatever it took with it, so
 * Undo puts it all back.
 *
 * Every query filters by user_id even though the connector's token is bound by
 * RLS, because Abood runs these with the service client, which is not.
 *
 * Deliberately absent, on engineering grounds:
 *   - Editing events mirrored from a subscribed calendar. The next sync
 *     overwrites them within five minutes, so the edit would silently revert.
 *   - Account deletion, AI keys, notification channels and linked chats.
 *     Abood is reachable over Telegram and iMessage, and those would let
 *     whoever holds the phone, or a hijacked chat, lock the owner out.
 *   - Changing a repeating class or repeating work as a whole. Their rows are
 *     generated by the app (lib/classes.ts, lib/series); single occurrences
 *     can be edited or removed here, the pattern is changed in the app.
 */

