const updatePlanSettings = tool({
  name: 'update_plan_settings',
  description:
    'How the work plan is made. study_hours sets the hours work may be planned in, per weekday: {"mon": "09:00-21:00", "sat": "off"}; weekdays not given keep their hours. add_days_off and remove_days_off take single dates ("I am off Saturday"). day_cap_minutes is the most work planned in a day. autoplan turns automatic planning on or off.',
  inputSchema: {
    type: 'object',
    properties: {
      study_hours: { type: 'object', additionalProperties: { type: 'string' } },
      add_days_off: { type: 'array', items: { type: 'string' } },
      remove_days_off: { type: 'array', items: { type: 'string' } },
      day_cap_minutes: { type: 'integer', minimum: 30, maximum: 720 },
      autoplan: { type: 'boolean' },
    },
    additionalProperties: false,
  },
  readOnly: false,
  async run(args, ctx) {
    const before = await must(ctx.db.from('app_settings').select('study_hours, plan_off_days, plan_day_cap, autoplan').eq('user_id', ctx.userId).single());
    const patch: Record<string, unknown> = {};
    const hours = args.study_hours as Record<string, unknown> | undefined;
    if (hours) {
      if (typeof hours !== 'object') throw new ToolError('"study_hours" must map weekdays to "HH:MM-HH:MM" or "off".');
      const next: Record<string, [number, number]> = { ...((before.study_hours as Record<string, [number, number]> | null) ?? Object.fromEntries(DAYS.map((_, i) => [String(i + 1), [540, 1260]]))) };
      for (const [k, v] of Object.entries(hours)) {
        const i = DAYS.indexOf(k.slice(0, 3).toLowerCase());
        if (i < 0) throw new ToolError(`"${k}" is not a weekday.`);
        if (v === 'off') delete next[String(i + 1)];
        else {
          const m = typeof v === 'string' ? /^(\d{2}:\d{2})-(\d{2}:\d{2})$/.exec(v.trim()) : null;
          if (!m) throw new ToolError(`Hours for ${k} must look like "09:00-21:00" or be "off".`);
          const from = toMinutes(m[1]);
          const to = m[2] === '24:00' ? 1440 : toMinutes(m[2]);
          if (!(to > from) || to > 1440) throw new ToolError(`Hours for ${k} must end after they start.`);
          next[String(i + 1)] = [from, to];
        }
      }
      patch.study_hours = next;
    }
    const add = dayList(args, 'add_days_off');
    const remove = new Set(dayList(args, 'remove_days_off'));
    if (add.length || remove.size) {
      const today = localDayKey(ctx.now, ctx.tz);
      patch.plan_off_days = [...new Set([...((before.plan_off_days as string[]) ?? []), ...add])].filter((d) => !remove.has(d) && d >= addDays(today, -30)).sort();
    }
    const cap = int(args, 'day_cap_minutes', 30, 720);
    if (cap !== null) patch.plan_day_cap = cap;
    if (args.autoplan !== undefined) patch.autoplan = bool(args, 'autoplan', true);
    if (!Object.keys(patch).length) throw new ToolError('Nothing to change was given.');
    const old = pick(before, patch);
    await update(ctx, 'app_settings', ctx.userId, patch);
    await commit(ctx, 'update_plan_settings', 'app_settings', ctx.userId, old, `Changed how the plan is made (${Object.keys(patch).join(', ').replace(/_/g, ' ')})`, () =>
      update(ctx, 'app_settings', ctx.userId, old),
    );
    return json({ updated: Object.keys(patch), plan: await replanAfter(ctx) });
  },
});

